/// `HEAD` of a workspace-relative checkout, abbreviated as `update` reports it.
fn short_head(fixture: &Fixture, rel: &str) -> String {
    common::git(
        &fixture.workspace.join(rel),
        &["rev-parse", "--short", "HEAD"],
    )
}

/// A cloned, synced workspace whose two source repositories are one commit
/// behind their origins — the starting point for most `update` cases.
fn behind_fixture() -> Fixture {
    let fixture = synced_fixture();
    for name in REPOS {
        fixture.commit_to_origin(name);
    }
    fixture
}

#[test]
