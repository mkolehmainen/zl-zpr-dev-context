#[test]
fn setup_leaves_existing_context_checkout_untouched() {
    let fixture = Fixture::new();
    // A local commit that the origin does not have: a fetch or a checkout would
    // be visible, and setup must perform neither.
    fixture.write(&format!("{CONTEXT}/LOCAL.md"), "local only\n");
    common::git(&fixture.context, &["add", "-A"]);
    common::git(&fixture.context, &["commit", "-m", "local"]);
    let head = common::git(&fixture.context, &["rev-parse", "HEAD"]);
    let branch = common::git(&fixture.context, &["rev-parse", "--abbrev-ref", "HEAD"]);
    fixture.commit_to_origin(CONTEXT);

    stdout_of(&fixture.run(&["setup"]));

    assert_eq!(common::git(&fixture.context, &["rev-parse", "HEAD"]), head);
    assert_eq!(
        common::git(&fixture.context, &["rev-parse", "--abbrev-ref", "HEAD"]),
        branch
    );
    assert_eq!(fixture.read(&format!("{CONTEXT}/LOCAL.md")), "local only\n");
}

