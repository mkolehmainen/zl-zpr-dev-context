//! Integration tests: the compiled binary driven against a throwaway workspace
//! built from local `file://` origins (spec §8.1). The cases for each command
//! land with that command, in Steps 6–10.

mod common;

use common::{CONTEXT, Fixture, REPOS};

/// The fixture assembles without network access, and the binary it drives runs.
#[test]
fn fixture_builds_and_binary_runs() {
    let fixture = Fixture::new();

    let output = fixture.run(&["--version"]);
    assert!(
        output.status.success(),
        "binary failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );

    // The context checkout is a real clone: it has a commit and an upstream.
    let sha = common::git(&fixture.context, &["rev-parse", "HEAD"]);
    assert_eq!(sha.len(), 40, "unexpected HEAD sha: {sha:?}");
    assert_eq!(
        common::git(&fixture.context, &["rev-parse", "--abbrev-ref", "@{u}"]),
        "origin/main"
    );

    // The shared context and its documentation reference are present, and the
    // manifest points at the local origins.
    assert!(
        fixture
            .read(&format!("{CONTEXT}/AGENTS.md"))
            .contains("docs/EXAMPLE.md")
    );
    assert!(fixture.exists(&format!("{CONTEXT}/docs/EXAMPLE.md")));
    assert!(
        fixture
            .read(&format!("{CONTEXT}/workspace.yaml"))
            .contains("file://")
    );

    // Source repositories are absent until cloned.
    assert!(!fixture.exists("zpr-core"));
    fixture.clone_repos();
    assert!(fixture.exists("zpr-core/README.md"));
}

/// Asserts the run succeeded, and returns its stdout.
fn stdout_of(output: &std::process::Output) -> String {
    assert!(
        output.status.success(),
        "command failed ({:?}): {}",
        output.status.code(),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8_lossy(&output.stdout).to_string()
}

/// A cloned workspace with the generated files already written, which is the
/// starting point for most of the `sync` cases.
fn synced_fixture() -> Fixture {
    let fixture = Fixture::new();
    fixture.clone_repos();
    stdout_of(&fixture.run(&["sync"]));
    fixture
}

#[test]
fn sync_creates_generated_files() {
    let fixture = Fixture::new();
    fixture.clone_repos();

    let out = stdout_of(&fixture.run(&["sync"]));
    // Two files per repository, all new.
    assert!(out.contains("4 created"), "unexpected summary: {out}");

    for name in REPOS {
        let agents = fixture.read(&format!("{name}/AGENTS.md"));
        assert!(agents.contains("Generated by zpr-dev"), "{name}: {agents}");
        assert!(agents.contains("# Shared ZPR Development Context"));
        assert!(agents.contains("Shared ZPR conventions for the fixture workspace."));

        let claude = fixture.read(&format!("{name}/CLAUDE.md"));
        assert!(claude.contains("Generated by zpr-dev"));
        assert!(claude.contains("[AGENTS.md](./AGENTS.md)"), "{claude}");
    }
}

#[test]
fn sync_twice_is_a_no_op() {
    let fixture = synced_fixture();
    let before: Vec<_> = REPOS
        .iter()
        .map(|name| fixture.mtime(&format!("{name}/AGENTS.md")))
        .collect();

    let out = stdout_of(&fixture.run(&["sync"]));
    assert!(
        out.contains("0 created, 0 updated, 4 unchanged"),
        "unexpected summary: {out}"
    );

    for (name, mtime) in REPOS.iter().zip(before) {
        assert_eq!(
            fixture.mtime(&format!("{name}/AGENTS.md")),
            mtime,
            "{name}: unchanged file was rewritten"
        );
    }
}

